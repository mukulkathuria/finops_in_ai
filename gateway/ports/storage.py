"""Object storage for raw files (spec section 2: S3-compatible in production, local disk in
development). Keys are generated by the gateway, never derived from user input."""

from collections.abc import AsyncIterator
from typing import BinaryIO, Protocol


class ObjectStore(Protocol):
    @property
    def name(self) -> str: ...

    async def put(self, key: str, data: BinaryIO, *, content_type: str) -> None:
        """Store all of `data` (read from its start) under `key`; readers never see a part."""
        ...

    async def stream(self, key: str) -> AsyncIterator[bytes]:
        """The object's bytes in chunks. Raises FileNotFoundError at once if it does not exist,
        so a response never starts for a missing object."""
        ...

    async def delete(self, key: str) -> None:
        """Remove the object; a missing object is not an error."""
        ...

    async def is_ready(self) -> bool:
        """Whether the store can take writes now (readiness probe)."""
        ...
